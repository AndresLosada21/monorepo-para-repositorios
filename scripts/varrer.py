"""Varredura de rastro de IA em um repositorio Git.

Percorre a arvore atual, o historico inteiro, os autores e committers e as mensagens de commit.
Sai com codigo 1 quando encontra algo. A skill que contem este script nao entra no proprio
escopo: ela tem, por natureza, as expressoes que a busca procura.
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

BINARIOS = {".png", ".jpg", ".jpeg", ".gif", ".ico", ".war", ".jar", ".pdf", ".xlsx", ".xls",
            ".docx", ".doc", ".jasper", ".mdb", ".zip", ".woff", ".woff2", ".ttf", ".class"}

# nomes de ferramenta e marcadores de autoria automatica, com limites de palavra.
# "cursor" e comum em CSS e "brief" em ingles corrente: ficam de fora para nao acusar codigo de tela.
FERRAMENTAS = (r"claude|opus|sonnet|chatgpt|gpt-\d|copilot|gemini|opencode|cliproxy|"
               r"superpowers|ponytail|codex|aider|windsurf|langchain|openai|anthropic")
# o nome de um modelo de linguagem
MODELOS = r"modelo de linguagem|intelig[êe]ncia artificial"
# o vocabulario do trabalho com agente. "ledger" e "skill" sao palavras correntes em
# codigo e ficam de fora, para nao acusar toda vez.
AGENTE = (r"sub-?agentes?|agentic|self-review|co-authored-by|as an ai|como um modelo")
# frases que traduzem "feito por ferramenta" em portugues
PORTUGUES = (r"orquestrador|automa[çc][ãa]o|gerado por (ia|modelo|agente)")

# cada grupo com seu proprio tratamento de maiusculas e de limites de palavra
PADRAO = re.compile(
    r"(?<![\w-])(?:" + FERRAMENTAS + r")(?![\w-])"
    r"|(?:" + MODELOS + r")"
    r"|(?<![\w-])(?:" + AGENTE + r")(?![\w-])"
    r"|(?<![\w-])(?:" + PORTUGUES + r")(?![\w-])", re.IGNORECASE)
# sigla solta e em maiusculas: nao vale dentro de identificador, caminho ou string de codigo
SIGLA = re.compile(r"(?<![\w`'\"/.-])(IA|AI)(?![\w`'\"/.-])")

# o codigo gerado por ferramenta de Java e legitimo: nao e rastro de IA
GERADOR_LEGITIMO = re.compile(
    r"(?i)generated by the (javatm|java\s*tm|jax-ws|jaxb)|"
    r"generated by .*\b(jaxb|jax-ws|wsgen|xjc)\b")

IGNORAR_ARQUIVO = {"package-lock.json"}


def _rodar(repo: Path, *args: str) -> str:
    r = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True,
                       encoding="utf-8", errors="replace")
    return r.stdout


def _caminho_relativo(repo: Path, caminho: Path) -> str:
    try:
        return str(caminho.relative_to(repo)).replace("\\", "/")
    except ValueError:
        return str(caminho)


def _achados_em_texto(texto: str, onde: str) -> list[str]:
    achados = []
    for n, linha in enumerate(texto.splitlines(), 1):
        if GERADOR_LEGITIMO.search(linha):
            continue
        m = PADRAO.search(linha) or SIGLA.search(linha)
        if m:
            achados.append(f"{onde}:{n}: [{m.group(0)}] {linha.strip()[:150]}")
    return achados


def _arvore(repo: Path, excecoes: set[Path]) -> list[str]:
    achados = []
    for caminho in repo.rglob("*"):
        if not caminho.is_file() or ".git" in caminho.parts:
            continue
        if caminho.suffix.lower() in BINARIOS or caminho.name in IGNORAR_ARQUIVO:
            continue
        if caminho in excecoes:
            continue
        try:
            texto = caminho.read_text(encoding="utf-8")
        except Exception:
            continue
        achados += _achados_em_texto(texto, _caminho_relativo(repo, caminho))
    return achados


def _historico(repo: Path, excecoes: set[Path]) -> list[str]:
    achados = []
    for linha in _rodar(repo, "log", "--all", "-p", "--format=%h").splitlines():
        if linha[:1] not in "+-":
            continue
        if GERADOR_LEGITIMO.search(linha):
            continue
        m = PADRAO.search(linha) or SIGLA.search(linha)
        if m:
            achados.append(f"historico: [{m.group(0)}] {linha[:150]}")
    return achados


def _autores(repo: Path) -> list[str]:
    achados = []
    for linha in _rodar(repo, "log", "--all", "--format=%an <%ae>|%cn <%ce>").splitlines():
        for parte in linha.split("|"):
            m = PADRAO.search(parte)
            if m:
                achados.append(f"autor: [{m.group(0)}] {parte.strip()}")
    return achados


def _mensagens(repo: Path) -> list[str]:
    achados = []
    for linha in _rodar(repo, "log", "--all", "--format=%s%n%b").splitlines():
        m = PADRAO.search(linha) or SIGLA.search(linha)
        if m:
            achados.append(f"mensagem: [{m.group(0)}] {linha.strip()[:150]}")
    return achados


def _excecoes(repo: Path, excecoes) -> set:
    """Excecoes resolvidas: tanto pelo caminho absoluto quanto pelo relativo ao repositorio."""
    resolvidas = set()
    for e in excecoes or []:
        caminho = Path(e)
        if caminho.is_absolute():
            resolvidas.add(caminho.resolve())
        else:
            resolvidas.add((repo / caminho).resolve())
    return resolvidas


def varredura(pasta: Path, excecoes: list[Path] | None = None) -> list[str]:
    """Devolve a lista de achados; vazia significa repositorio limpo."""
    repo = Path(pasta)
    exc = _excecoes(repo, excecoes)
    achados = []
    achados += _arvore(repo, exc)
    achados += _historico(repo, exc)
    achados += _autores(repo)
    achados += _mensagens(repo)
    return achados


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Acha rastro de IA em um repositorio Git.")
    ap.add_argument("repositorio", help="pasta do repositorio")
    ap.add_argument("--historico", action="store_true", help="inclui historico, autores e mensagens")
    ap.add_argument("--excecao", action="append", default=[], help="caminho a ignorar (repetivel)")
    args = ap.parse_args(argv)

    repo = Path(args.repositorio)
    if not repo.exists():
        print(f"pasta inexistente: {repo}")
        return 2

    if args.historico:
        # sem historico nao ha o que varrer: dizer 'limpo' seria mentira
        if not (repo / ".git").exists():
            print(f"{repo.name}: nao e um repositorio git, a varredura de historico nao se aplica")
            return 2
        achados = varredura(repo, [Path(e) for e in args.excecao])
    else:
        achados = _arvore(repo, _excecoes(repo, [Path(e) for e in args.excecao]))

    print(f"{repo.name}: {len(achados)} achados")
    for a in achados[:60]:
        print("  ", a)
    return 1 if achados else 0


if __name__ == "__main__":
    sys.exit(main())
